"use strict";
/* Each project owns one Pages site with only its latest released score.
   SVG notation is paired with real barline rectangles generated by ScoreKit.
   Printed measure numbers may repeat during playback; clicking selects the
   FIRST performance occurrence, including a D.C. al Fine reprise. */
const $ = id => document.getElementById(id);
const SVG_NS = "http://www.w3.org/2000/svg";
const message = text => $("message").textContent = text;
let info=null, manifest=null, timeline=null;
let selectedRegion=null, lastPage="", pendingSeek=null, trackChange=0;
let playbackFrame=null, playAfterSeek=false, seekGeneration=0;
const audio = $("audio");

function choices(select, rows) {
  select.replaceChildren();
  for (const [value, label] of rows) {
    const option = document.createElement("option");
    option.value = value;
    option.textContent = label;
    select.append(option);
  }
}
function viewLabel(id, view) {
  const types = {"score":"Партитура","concert-score":"Концертный строй",
                 "individual":"Партия","combined":"Объединённая партия"};
  const name = view.label || id.replaceAll("-", " ");
  return (types[view.kind] || "Ноты") + " · " + name;
}
function trustedPath(path, prefix, suffix) {
  if (typeof path !== "string" || !path.startsWith(prefix) ||
      !path.toLowerCase().endsWith(suffix) || path.startsWith("/") ||
      path.includes("\\") || path.split("/").some(x => !x || x === "." || x === ".."))
    throw Error("Некорректный путь ресурса: " + path);
  return path;
}
async function getJSON(url) {
  const response=await fetch(url,{cache:"no-store"});
  if(!response.ok)throw Error("HTTP "+response.status+": "+url);
  return response.json();
}
function displayMarkdown(text) {
  const root = $("readme");
  if (window.marked?.parse && window.DOMPurify?.sanitize) {
    root.innerHTML = DOMPurify.sanitize(marked.parse(text, {gfm:true,breaks:false}), {
      USE_PROFILES:{html:true}
    });
    for(const link of root.querySelectorAll("a[href]")) {
      const url = new URL(link.getAttribute("href"), location.href);
      if(!["https:","http:","mailto:"].includes(url.protocol)) {
        link.removeAttribute("href");
      } else {
        link.href=url.href;
        link.target="_blank";
        link.rel="noopener noreferrer";
      }
    }
  } else {
    // The score still works if the optional Markdown libraries are blocked.
    root.textContent=text;
  }
}
async function boot() {
  try {
    info=await getJSON("./latest.json");
    if(info.schema!=="scorekit-project-site-v1")throw Error("Неподдерживаемый формат сайта");
    [manifest,timeline]=await Promise.all([
      getJSON("./latest/viewer/manifest.json"),
      getJSON("./latest/viewer/timeline.json")
    ]);
    if(!manifest?.views || !Object.keys(manifest.views).length ||
       !Array.isArray(timeline?.measures) || !timeline.measures.length)
      throw Error("Нет данных нот и времени воспроизведения");
    $("heading").textContent=[info.title,info.orchestra].filter(Boolean).join(" · ");
    $("version").textContent="Актуальная версия: "+info.tag;
    document.title=(info.title||"Партитура")+" — ScoreKit";
    if(info.release_url){$("release").href=info.release_url;$("release").hidden=false;}
    if(typeof info.repo==="string" && /^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/.test(info.repo)){
      $("repository").href="https://github.com/"+info.repo;
      $("repository").hidden=false;
    }
    choices($("view"),Object.entries(manifest.views).map(([id,v])=>[id,viewLabel(id,v)]));
    choices($("track"),[["","Без звука"],...manifest.audio_tracks.map(t=>[t.id,t.label])]);
    $("view").disabled=$("track").disabled=false;
    $("seek").max=String(timeline.measures.length-1);$("seek").disabled=false;
    const param=new URL(location.href).searchParams.get("view");
    if(param && Object.hasOwn(manifest.views,param))$("view").value=param;
    if(info.readme_available){
      const response=await fetch("./latest/README.md",{cache:"no-store"});
      displayMarkdown(response.ok ? await response.text() : "README недоступен");
    }else displayMarkdown("README выбранной редакции отсутствует.");
    message("");
    showView();
  }catch(e){message("Не удалось открыть партитуру: "+e.message+
    ". Проверьте наличие опубликованного релиза с архивами audio и viewer.");
    console.error("ScoreKit viewer:",e);}
}
function measureNumber(id) {
  const match=/^measure-(\d+)$/.exec(id||"");
  return match?Number(match[1]):null;
}
function regionForPrinted(measureNumberValue, view) {
  const areas=view?.measure_areas||[];
  const found=areas.find(a=>measureNumber(a.measure_id)===measureNumberValue);
  if(found)return found;
  // A multimeasure rest has a single physical box for several silent bars.
  // Only reuse the preceding region when the following mark is on the
  // same SVG page, so a system or page break is never fabricated.
  const prior=areas.filter(a=>measureNumber(a.measure_id)<measureNumberValue)
    .sort((a,b)=>measureNumber(b.measure_id)-measureNumber(a.measure_id))[0];
  const next=areas.filter(a=>measureNumber(a.measure_id)>measureNumberValue)
    .sort((a,b)=>measureNumber(a.measure_id)-measureNumber(b.measure_id))[0];
  // Never extend a rest across a system break: a physical barline is missing.
  return prior && next && prior.page===next.page &&
    Math.abs(prior.y-next.y)<0.8 ? prior : null;
}
function markMeasure(measureNumberValue) {
  const view=manifest?.views?.[$("view").value];
  const area=regionForPrinted(measureNumberValue,view);
  const next=area ? $("pages").querySelector(
    '.measure-region[data-page="'+area.page+'"][data-measure="'+area.measure_id+'"]'
  ) : null;
  if(selectedRegion===next)return;
  selectedRegion?.classList.remove("active");
  selectedRegion=next;
  selectedRegion?.classList.add("active");
  if(next && !audio.paused && String(area.page)!==lastPage){
    const page=$("pages").querySelector('.page[data-page="'+area.page+'"]');
    if(page && !page.matches(":hover")){
      lastPage=String(area.page);
      page.scrollIntoView({behavior:"auto",block:"nearest"});
    }
  }
}
function seekPrinted(number) {
  const occurrence=timeline?.measures?.find(m=>m.printed_number===number);
  if(!occurrence)return;
  // Seek exactly to the start of the bar. All player updates use the same clock.
  seekSeconds(occurrence.start_ms/1000, true);
}
function seekSeconds(seconds, startPlayback=false) {
  if(!Number.isFinite(seconds)||seconds<0)return;
  if(!audio.getAttribute("src")){
    const defaultTrack=manifest?.audio_tracks?.find(t=>t.id==="orchestra") ||
                       manifest?.audio_tracks?.[0];
    if(!defaultTrack)return;
    pendingSeek=seconds;
    playAfterSeek=startPlayback;
    $("track").value=defaultTrack.id;
    setTrack();
    return;
  }
  if(audio.readyState < HTMLMediaElement.HAVE_METADATA){
    pendingSeek=seconds;
    playAfterSeek=startPlayback;
    return;
  }
  const target=Math.min(seconds,Number.isFinite(audio.duration)?
      Math.max(0,audio.duration-.05):seconds);
  const resume=startPlayback || !audio.paused;
  const token=++seekGeneration;
  if(Math.abs(audio.currentTime-target)<0.012 && !audio.seeking){
    updateTime();
    if(resume && audio.paused)audio.play().catch(()=>{});
    return;
  }
  // Let the media decoder complete a random seek before resuming.
  // This prevents the old buffered position from playing briefly on mobile.
  audio.pause();
  audio.addEventListener("seeked",()=>{
    if(token!==seekGeneration)return;
    updateTime();
    if(resume)audio.play().catch(()=>{});
  },{once:true});
  audio.currentTime=target;
  updateTime();
}
function preferredTrackForView(id,view){
  if(view.kind==="score" || view.kind==="concert-score")
    return manifest.audio_tracks.find(t=>t.id==="orchestra")?.id || manifest.audio_tracks[0]?.id || "";
  if(manifest.audio_tracks.some(t=>t.id===id))return id;
  // A combined desk has multiple musicians. Until true multi-track mixing
  // is available, use the complete orchestra rather than an arbitrary stem.
  return manifest.audio_tracks.find(t=>t.id==="orchestra")?.id || manifest.audio_tracks[0]?.id || "";
}
function showView() {
  if(!manifest)return;
  const id=$("view").value,view=manifest.views[id];if(!view)return;
  $("pages").replaceChildren();
  selectedRegion=null;lastPage="";
  $("notation").scrollTop=0;
  $("notation").scrollLeft=0;
  $("notation").dataset.kind=view.kind;
  const fragment=document.createDocumentFragment();
  for(let i=0;i<view.pages.length;i++){
    const path=trustedPath(view.pages[i],"svg/",".svg");
    const wrapper=document.createElement("div");wrapper.className="page";
    wrapper.dataset.page=String(i+1);
    const img=document.createElement("img");
    img.alt="Страница "+(i+1)+" · "+id;
    img.loading=i===0?"eager":"lazy";
    img.decoding="async";
    img.src="./latest/viewer/"+path;
    wrapper.append(img);
    const areas=(view.measure_areas||[]).filter(a=>Number(a.page)===i+1);
    const box=view.page_viewboxes?.[String(i+1)];
    if(box && box.length===4 && areas.length) {
      const svg=document.createElementNS(SVG_NS,"svg");
      svg.classList.add("measure-layer");
      svg.setAttribute("viewBox",box.join(" "));
      svg.setAttribute("preserveAspectRatio","none");
      svg.setAttribute("aria-label","Интерактивные такты");
      for(const area of areas){
        if(![area.x,area.y,area.width,area.height].every(Number.isFinite))continue;
        const rect=document.createElementNS(SVG_NS,"rect");
        rect.setAttribute("x",area.x);
        rect.setAttribute("y",area.y);
        rect.setAttribute("width",area.width);
        rect.setAttribute("height",area.height);
        rect.classList.add("measure-region");
        rect.dataset.page=String(i+1);
        rect.dataset.measure=area.measure_id;
        rect.setAttribute("tabindex","0");
        rect.setAttribute("role","button");
        rect.setAttribute("aria-label","Перейти к такту "+measureNumber(area.measure_id));
        const seek=()=>seekPrinted(measureNumber(area.measure_id));
        rect.addEventListener("click",seek);
        rect.addEventListener("keydown",e=>{
          if(e.key==="Enter"||e.key===" "){e.preventDefault();seek();}
        });
        svg.append(rect);
      }
      wrapper.append(svg);
    }
    fragment.append(wrapper);
  }
  $("pages").append(fragment);
  const url=new URL(location.href);url.searchParams.set("view",id);
  history.replaceState(null,"",url);
  updateTime();
  const preferred=preferredTrackForView(id,view);
  if($("track").value!==preferred){
    $("track").value=preferred;
    setTrack();
  }
}
function setTrack() {
  if(!manifest)return;
  const track=manifest.audio_tracks.find(t=>t.id===$("track").value);
  if(!track){
    ++trackChange;
    ++seekGeneration;
    playAfterSeek=false;
    audio.pause();audio.removeAttribute("src");audio.load();
    updateTime();
    return;
  }
  const path=trustedPath(track.path.replace(/^(\.\.\/)+/,""),"audio/",".mp3");
  const previousTime=audio.currentTime||0,playing=!audio.paused;
  const requestedRate=Number($("speed").value);
  ++seekGeneration;
  const token=++trackChange;
  audio.src="./latest/"+path;
  audio.load();
  audio.addEventListener("loadedmetadata",()=>{
    if(token!==trackChange)return;
    const target=pendingSeek??previousTime;
    const resume=playing || playAfterSeek;
    pendingSeek=null;
    playAfterSeek=false;
    audio.playbackRate=requestedRate;
    seekSeconds(target,resume);
  },{once:true});
  message("");
}
function updateTime() {
  if(!timeline?.measures?.length || !manifest)return;
  const ms=(Number.isFinite(audio.currentTime)?audio.currentTime:0)*1000,measures=timeline.measures;
  let low=0,high=measures.length;
  while(low<high){
    const mid=(low+high)>>1;
    if(measures[mid].start_ms<=ms)low=mid+1;else high=mid;
  }
  const index=Math.max(0,low-1),measure=measures[index];
  $("seek").value=String(index);
  $("position").textContent="Такт "+measure.printed_number+" / "+timeline.printed_measures+
    (measure.number>timeline.printed_measures?" · реприза":"");
  markMeasure(audio.paused ? null : measure.printed_number);
}
$("view").addEventListener("change",showView);
$("track").addEventListener("change",setTrack);
audio.addEventListener("timeupdate",updateTime);
audio.addEventListener("seeked",updateTime);
audio.addEventListener("loadedmetadata",updateTime);
audio.addEventListener("ended",()=>{stopFrames();updateTime();});
function stopFrames(){
  if(playbackFrame!==null) cancelAnimationFrame(playbackFrame);
  playbackFrame=null;
}
function paintWhilePlaying(){
  playbackFrame=null;
  if(audio.paused)return;
  updateTime();
  playbackFrame=requestAnimationFrame(paintWhilePlaying);
}
audio.addEventListener("play",()=>{stopFrames();paintWhilePlaying();});
audio.addEventListener("pause",()=>{stopFrames();updateTime();});
$("restart").addEventListener("click",()=>seekSeconds(0));
$("speed").addEventListener("input",()=>{
  const rate=Number($("speed").value);
  audio.playbackRate=rate;
  $("speedValue").textContent=Math.round(rate*100)+"%";
  $("speedSummary").textContent=Math.round(rate*100)+"%";
});
// audio.currentTime is in media seconds, independent of playbackRate.
// MIDI timeline timestamps remain valid when playback speed changes.

$("seek").addEventListener("input",()=>{
  const measure=timeline?.measures?.[Number($("seek").value)];
  if(measure)seekSeconds(measure.start_ms/1000);
});
boot();
